def replace_once(old: str, new: str, label: str) -> None:
    global text
    count = text.count(old)
    if count != 1:
        raise SystemExit(f"{label}: expected 1 match, found {count}")
    text = text.replace(old, new, 1)


def replace_section(start_heading: str, next_heading: str, new_section: str) -> None:
    global text
    start = text.find(start_heading)
    end = text.find(next_heading, start + len(start_heading))
    if start < 0 or end < 0:
        raise SystemExit(f"section not found: {start_heading} -> {next_heading}")
    text = text[:start] + new_section.rstrip() + "\n\n---\n\n" + text[end:]


